/**
 * Writes public/firebase-config.js from .env so the hosted join page and the
 * app can never drift onto different Firebase projects.
 *
 * Only the project id and web API key go in. Both are public by design — they
 * name the project, they do not authorise anything. firestore.rules is the
 * security boundary.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const envPath = path.join(root, '.env');

if (!fs.existsSync(envPath)) {
  console.error('No .env found. Copy .env.example to .env and fill it in first.');
  process.exit(1);
}

const env = Object.fromEntries(
  fs
    .readFileSync(envPath, 'utf8')
    .split(/\r?\n/)
    .filter((line) => line.trim() && !line.trim().startsWith('#') && line.includes('='))
    .map((line) => {
      const i = line.indexOf('=');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    })
);

const projectId = env.EXPO_PUBLIC_FIREBASE_PROJECT_ID;
const apiKey = env.EXPO_PUBLIC_FIREBASE_API_KEY;

if (!projectId || !apiKey) {
  console.error('.env is missing EXPO_PUBLIC_FIREBASE_PROJECT_ID or _API_KEY.');
  process.exit(1);
}

const out = `// GENERATED by scripts/gen-public-config.js — do not edit by hand.
// Run \`npm run config\` after changing .env.
window.FIREBASE_CONFIG = ${JSON.stringify({ projectId, apiKey }, null, 2)};
`;

fs.writeFileSync(path.join(root, 'public', 'firebase-config.js'), out);
console.log(`public/firebase-config.js -> ${projectId}`);
